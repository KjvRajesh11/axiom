"""Unit and integration tests for Axiom 2.2 AST Transformation Module.

Tests:
- Accepted canonical AST transformation on valid 3-deep loop nest (matmul_reference).
- Precondition rejection when side effects (function calls) are detected in loop body.
- Precondition rejection when non-canonical loop bounds are present.
- Precondition rejection on mutable/aliased input pointers.
- Independent candidate compilation and numerical verification.
- Graceful handling of invalid C++ syntax.
"""

import os
import tempfile
import pytest

from axiom.ast_transform import ClangASTEngine, ConstrainedLoopTransformer


def test_ast_dump_and_function_finding():
    engine = ClangASTEngine()
    ast = engine.dump_ast_json("cpp/workloads/matmul/matmul_reference.cpp")
    assert ast is not None
    assert "inner" in ast

    func = engine.find_function_in_ast(ast, "matmul_reference")
    assert func is not None
    assert func.get("name") == "matmul_reference"


def test_ast_loop_interchange_accepted():
    transformer = ConstrainedLoopTransformer()
    with tempfile.TemporaryDirectory() as tmpdir:
        cand_path = os.path.join(tmpdir, "matmul_ast_candidate.cpp")
        res = transformer.transform_loop_interchange(
            source_file="cpp/workloads/matmul/matmul_reference.cpp",
            func_name="matmul_reference",
            output_candidate_path=cand_path,
            candidate_id="matmul_ast_interchanged",
        )

        assert res.success is True
        assert res.preconditions.satisfied is True
        assert res.compilation_passed is True
        assert res.correctness_passed is True
        assert res.max_relative_error is not None
        assert res.max_relative_error < 1e-4
        assert os.path.exists(cand_path)

        with open(cand_path, "r") as f:
            content = f.read()
        assert "AUTOMATICALLY GENERATED BY AXIOM 2.2 AST TRANSFORMATION ENGINE" in content
        assert "AST-Driven Canonical Loop Interchange (i-j-k -> i-k-j)" in content
        assert "matmul_ast_interchanged" in content


def test_ast_reject_side_effects():
    # Loop containing a function call (side effect)
    src_with_side_effects = """#include "axiom_utils.hpp"
#include <cstdio>

namespace axiom {
void matmul_side_effects(const float* A, const float* B, float* C, int N) {
    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < N; ++j) {
            float sum = 0.0f;
            for (int k = 0; k < N; ++k) {
                sum += A[i * N + k] * B[k * N + j];
                std::printf("debug\\n"); // FORBIDDEN SIDE EFFECT
            }
            C[i * N + j] = sum;
        }
    }
}
}
"""
    transformer = ConstrainedLoopTransformer()
    with tempfile.TemporaryDirectory() as tmpdir:
        src_path = os.path.join(tmpdir, "matmul_side_effect.cpp")
        with open(src_path, "w") as f:
            f.write(src_with_side_effects)

        cand_path = os.path.join(tmpdir, "matmul_out.cpp")
        res = transformer.transform_loop_interchange(
            source_file=src_path,
            func_name="matmul_side_effects",
            output_candidate_path=cand_path,
        )

        assert res.success is False
        assert res.preconditions.satisfied is False
        assert any("side effects" in r.lower() for r in res.preconditions.rejection_reasons)
        assert res.rejection_reason is not None


